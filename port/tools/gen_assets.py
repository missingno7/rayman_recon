"""Generate the port's external data assets from the player's own RAYMAN.EXE (build step).

Some initialised tables of the original program are deliberately not reconstructed as source but taken from the
user's executable at build time (user decision 2026-10-22, docs/LINK.md; tools/link.py does the same for the DOS
relink): PalPlasma (2:05f70, 48 B) and Def_Bande (2:080fc, 144,000 B). The generated C is written to the build
directory only; it is never tracked. The executable must be the pinned GOG v1.21 file (config/oracles.json).

    python port/tools/gen_assets.py RAYMAN.EXE OUT.c
"""
import hashlib
import os
import json
import sys
from pathlib import Path

PORT = Path(__file__).resolve().parents[1]
ROOT = Path(os.environ["RAY_ROOT"]).resolve() if os.environ.get("RAY_ROOT") else PORT.parent
sys.path.insert(0, str(ROOT / "tools"))
import pmw1  # noqa: E402

ASSETS = [("PalPlasma", 0x5f70, 48), ("Def_Bande", 0x80fc, 144000)]


def main(argv):
    exe_path, out = Path(argv[1]), Path(argv[2])
    oracles = json.loads((ROOT / "config" / "oracles.json").read_text(encoding="utf-8"))
    pinned = oracles["oracles"][oracles["primary"]]
    exe = exe_path.read_bytes()
    if hashlib.sha256(exe).hexdigest() != pinned["sha256"]:
        raise SystemExit(f"{exe_path} is not the GOG v1.21 RAYMAN.EXE this port is built from (sha256 mismatch)")
    data = dict((i, d) for i, d, _ in pmw1.PMW1(exe).object_data())[2]
    text = ["/* Generated by port/tools/gen_assets.py from the user's RAYMAN.EXE (GOG v1.21); not tracked. */",
            '#include "rtypes.h"', '#include "palette.h"', '#include "screen_types.h"', ""]
    for name, start, size in ASSETS:
        b = data[start:start + size]
        if name == "PalPlasma":
            text.append("rgb_t PalPlasma[16] = {" + ",".join(
                "{%d,%d,%d}" % tuple(b[i:i + 3]) for i in range(0, size, 3)) + "};")
        else:
            rows = []
            for at in range(0, size, 8):
                rows.append("%d,%s" % (int.from_bytes(b[at:at + 2], "little"), ",".join(str(x) for x in b[at + 2:at + 8])))
            # Def_Bande[6][10][300] of {u16 length; 6 bytes}: one flat scalar list, filled in row-major order by
            # brace elision (a braced record would initialise a whole [10][300] sub-array instead).
            text.append("def_bande_t Def_Bande[6][10][300] = {" + ",\n".join(rows) + "};")
        # FNV-1a of the source bytes: tests/unit_tests.c compares it with the compiled table's memory.
        h = 1469598103934665603
        for x in b:
            h = ((h ^ x) * 1099511628211) & 0xFFFFFFFFFFFFFFFF
        text.append("const unsigned long long port_asset_fnv_%s = 0x%016xULL;" % (name, h))
    out.parent.mkdir(parents=True, exist_ok=True)
    new = "\n".join(text) + "\n"
    if not out.exists() or out.read_text() != new:
        out.write_text(new)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))

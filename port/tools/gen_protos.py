"""Generate port/game/protos/<unit>.h: prototypes for functions a historical unit calls without a declaration.

Watcom 10.6 accepted these calls (C89 implicit `int f()`), and on its 32-bit register ABI the results were
correct because every callee returns in EAX. A native 64-bit compiler would assume `int` and lose the upper half
of a pointer result or read garbage above an s16/u8 result. The port therefore pre-includes, per unit, the true
prototypes of exactly the implicitly called functions. The declarations come from the semantic registries
(docs/semantics/*.json, `c_type` of each function entity, checked against the code by tools/semantics.py) or,
for port boundary services, from compat headers (BOUNDARY below). The historical sources are not edited.

    python port/tools/gen_protos.py            # regenerate
    python port/tools/gen_protos.py --check    # fail if a committed header is stale
"""
import glob
import json
import os
import re
import subprocess
import sys
from pathlib import Path

PORT = Path(__file__).resolve().parents[1]
ROOT = Path(os.environ["RAY_ROOT"]).resolve() if os.environ.get("RAY_ROOT") else PORT.parent
OUT = PORT / "game" / "protos"

# Boundary services the historical code calls implicitly; their contracts are in port/docs/BOUNDARY.md.
BOUNDARY = {
    "synchro": "void synchro(void)",
    "endsynchro": "void endsynchro(void)",
    "set_speaker_on": "void set_speaker_on(void)",
    "set_speaker_off": "void set_speaker_off(void)",
    "default_sprite_clipping": "void default_sprite_clipping(void)",
}
# Headers a prototype header may rely on (each unit's own includes decide; see header_for()).
SHARED = ["rtypes.h", "obj.h", "map.h", "palette.h", "game.h"]


def gcc():
    return os.environ.get("CC", "gcc")


def implicit_calls(src):
    cmd = [gcc(), "-fsyntax-only", "-std=gnu11", "-funsigned-char", "-Wno-unknown-pragmas",
           "-Wimplicit-function-declaration", "-include", str(PORT / "compat/include/port_watcom.h"),
           "-I", str(PORT / "compat/include"), "-I", str(ROOT / "src/include"), "-I", str(ROOT / "src"), str(src)]
    err = subprocess.run(cmd, capture_output=True, text=True).stderr
    return sorted(set(re.findall(r"implicit declaration of function '(\w+)'", err)))


def registry_prototypes():
    defs = {}
    for p in sorted(glob.glob(str(ROOT / "docs/semantics/*.json"))):
        for e in json.load(open(p, encoding="utf-8"))["entities"]:
            if e["kind"] == "function":
                defs[e["current_name"]] = (Path(p).name, e["c_type"].replace(" * restrict", " *"))
    return defs


def includes_of(src):
    """Every header the unit includes, directly or through its local headers."""
    cmd = [gcc(), "-MM", "-I", str(PORT / "compat/include"), "-I", str(ROOT / "src/include"),
           "-I", str(ROOT / "src"), str(src)]
    deps = subprocess.run(cmd, capture_output=True, text=True).stdout.replace("\\\n", " ").split()
    return [Path(d).name for d in deps if d.endswith(".h")]


def render(unit, src, names, defs):
    own = includes_of(src)
    lines = [f"/* Generated by port/tools/gen_protos.py for src/{unit}.c: prototypes of the functions it calls",
             "   without a declaration (native 64-bit return values need them). Do not edit. */",
             f"#ifndef PORT_PROTOS_{unit.upper()}_H", f"#define PORT_PROTOS_{unit.upper()}_H"]
    for h in SHARED:
        if h in own:
            lines.append(f'#include "{h}"')
    for n in names:
        if n in BOUNDARY:
            lines.append(f"{BOUNDARY[n]};  /* port boundary service */")
        elif n in defs:
            lines.append(f"{defs[n][1]};  /* {defs[n][0]} */")
        else:
            raise SystemExit(f"{unit}: no declaration source for {n}")
    lines += ["#endif", ""]
    return "\n".join(lines)


def main(argv):
    check = "--check" in argv
    defs = registry_prototypes()
    OUT.mkdir(parents=True, exist_ok=True)
    stale = 0
    wanted = set()
    for src in sorted((ROOT / "src").glob("*.c")):
        unit = src.stem
        names = implicit_calls(src)
        path = OUT / f"{unit}.h"
        # a committed header hides the implicit calls; take its names too
        if path.exists():
            names = sorted(set(names) | set(re.findall(r"\b(\w+)\([^)]*\);  /\*", path.read_text())))
        if not names:
            continue
        wanted.add(path.name)
        text = render(unit, src, names, defs)
        if not path.exists() or path.read_text() != text:
            stale += 1
            if not check:
                path.write_text(text, newline="\n")
    for p in OUT.glob("*.h"):
        if p.name not in wanted:
            stale += 1
            if not check:
                p.unlink()
    print(f"{len(wanted)} prototype headers, {stale} {'stale' if check else 'written'}")
    return 1 if check and stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
